-- ═══════════════════════════════════════════════════════════════════════
-- HISTORIAL DE ESTADOS DE LOS PEDIDOS (P2-20, 2ª prueba integral, 29/10/2026)
--
-- Qué pasaba: entre el 27/10 y el 28/10 los pedidos 001945, 001956 y 001972
-- volvieron de "sistema viejo" a "impreso" y no había forma de saber quién ni
-- cuándo (pedidos.actualizado_por quedaba vacío). La causa: reimprimir un pedido
-- lo pasaba a "impreso" en cualquier estado (ya corregido en el código).
--
-- Qué hace: cada vez que un pedido nace o cambia de estado — lo haga quien lo
-- haga (pantalla, app, servidor, otra función de la base) — queda una fila en
-- pedidos_estados_historial con el estado anterior, el nuevo, quién y cuándo.
--   * Quién: el usuario que hizo el cambio (sesión del ERP o de la app). Si el
--     cambio lo hizo el servidor con la clave de servicio, el que el código
--     anotó en pedidos.actualizado_por en ese mismo cambio; si no anotó nadie,
--     queda vacío y "via" dice que fue el servidor.
--   * pedidos.actualizado_por pasa a ser siempre el último que cambió el estado
--     (antes podía quedar el de un cambio anterior).
--
-- Solo agrega una tabla y un disparador. No cambia datos. IDEMPOTENTE.
-- ═══════════════════════════════════════════════════════════════════════

create table if not exists public.pedidos_estados_historial (
  id               bigint generated by default as identity primary key,
  pedido_id        uuid not null references public.pedidos(id) on delete cascade,
  estado_anterior  text,
  estado_nuevo     text,
  usuario_id       uuid,
  via              text,
  cambiado_at      timestamptz not null default now()
);

comment on table public.pedidos_estados_historial is
  'P2-20: cada cambio de estado de un pedido (quién, cuándo, de qué estado a cuál). Lo llena el disparador trg_pedidos_historial_estado.';
comment on column public.pedidos_estados_historial.via is
  'Quién hizo el cambio en la base: authenticated (sesión del usuario), service_role (servidor), o el rol de la base';

create index if not exists idx_pedidos_estados_historial_pedido on public.pedidos_estados_historial (pedido_id, cambiado_at);

alter table public.pedidos_estados_historial enable row level security;
drop policy if exists pedidos_estados_historial_leer on public.pedidos_estados_historial;
create policy pedidos_estados_historial_leer on public.pedidos_estados_historial
  for select to authenticated using (true);
grant select on public.pedidos_estados_historial to authenticated;
grant all on public.pedidos_estados_historial to service_role;

-- Antes del cambio: actualizado_por = quien cambia el estado (no el de antes)
create or replace function public.trg_pedidos_estado_quien()
returns trigger
language plpgsql as $fn$
declare
  v_uid uuid := auth.uid();
begin
  if new.estado is distinct from old.estado then
    if v_uid is not null then
      new.actualizado_por := v_uid;
    elsif new.actualizado_por is not distinct from old.actualizado_por then
      -- El servidor no dijo quién: no dejar el de un cambio anterior
      new.actualizado_por := null;
    end if;
  end if;
  return new;
end;
$fn$;

-- Después del alta o del cambio: una fila de historial
create or replace function public.trg_pedidos_historial_estado()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_via text := coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role', current_user::text);
begin
  if tg_op = 'INSERT' then
    insert into pedidos_estados_historial (pedido_id, estado_anterior, estado_nuevo, usuario_id, via)
    values (new.id, null, new.estado, coalesce(auth.uid(), new.creado_por, new.actualizado_por), v_via);
  elsif new.estado is distinct from old.estado then
    insert into pedidos_estados_historial (pedido_id, estado_anterior, estado_nuevo, usuario_id, via)
    values (new.id, old.estado, new.estado, coalesce(auth.uid(), new.actualizado_por), v_via);
  end if;
  return null;
end;
$fn$;

drop trigger if exists trg_pedidos_estado_quien on public.pedidos;
create trigger trg_pedidos_estado_quien
  before update of estado on public.pedidos
  for each row execute function public.trg_pedidos_estado_quien();

drop trigger if exists trg_pedidos_historial_estado on public.pedidos;
create trigger trg_pedidos_historial_estado
  after insert or update of estado on public.pedidos
  for each row execute function public.trg_pedidos_historial_estado();

