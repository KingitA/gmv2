-- JARVIS — "QUIÉN HIZO QUÉ" (05/11/2026)
--
-- Pedido de Juan: cada movimiento tiene que tener un responsable y Jarvis
-- tiene que poder decir quién fue. Revisando la base faltaban dos cosas:
--
-- 1) Cambios de datos de un ARTÍCULO: solo quedaba el último que lo tocó
--    (articulos.actualizado_por) y el historial de precios (qué y cuándo, pero
--    NO quién). Ahora cada campo que cambia deja una fila en articulos_cambios:
--    qué campo, cómo estaba, cómo quedó, quién y cuándo.
--      * Quién: el usuario de la sesión (pantalla de Artículos, app). Si el
--        cambio lo hizo el servidor, el que el código anotó en
--        articulos.actualizado_por en ese mismo cambio; si no anotó a nadie,
--        queda vacío y "via" dice que fue el servidor (Jarvis lo dice así).
--      * No se anotan el stock (eso ya lo cuenta el kardex) ni columnas
--        internas (búsqueda, embedding, fechas de actualización).
--
-- 2) Pagos a PROVEEDORES: la orden de pago guardaba quién la ARMÓ
--    (usuario_creador) — eso vale como AUTORIZACIÓN (decisión de Juan 05/11) —,
--    pero no quién la confirmó ni quién la anuló. Se agregan confirmado_por /
--    confirmado_at y anulado_por / anulado_at; los completan las pantallas al
--    confirmar, anular o cancelar (no cambia la función op_confirmar).
--
-- 3) VENCIMIENTOS (gastos, servicios, impuestos, facturas de proveedor): no
--    guardaban NADA de quién. Si alguien marcaba "pagado" el de EDES (que sale
--    sin orden de pago), se perdía quién y cuándo. Ahora:
--      * vencimientos.creado_por / actualizado_por / pagado_por / pagado_at;
--      * vencimientos_historial: cada alta y cada cambio de estado, monto o
--        fecha (antes → después, quién, cuándo, con qué orden de pago). Inborrable.
--    Quién: la sesión del usuario, o el que el código anota en
--    actualizado_por en ese mismo cambio (las pantallas lo mandan siempre).
--    Si lo pagó una orden de pago (op_confirmar), queda la orden: quién la armó.
--
-- Solo agrega tablas, columnas y disparadores. No cambia datos.
-- IDEMPOTENTE: se puede correr más de una vez.
-- ═══════════════════════════════════════════════════════════════════════

-- ─── 1. Cambios de artículos ───────────────────────────────────────────
create table if not exists public.articulos_cambios (
  id           bigint generated by default as identity primary key,
  articulo_id  uuid not null references public.articulos(id) on delete cascade,
  campo        text not null,
  antes        text,
  despues      text,
  usuario_id   uuid,
  via          text,
  cambiado_at  timestamptz not null default now()
);

comment on table public.articulos_cambios is
  'Jarvis 05/11/2026: cada campo de un artículo que cambia (antes, después, quién, cuándo). Lo llena trg_articulos_cambios. No se borra ni se edita.';

create index if not exists idx_articulos_cambios_articulo on public.articulos_cambios (articulo_id, cambiado_at);
create index if not exists idx_articulos_cambios_fecha on public.articulos_cambios (cambiado_at);

alter table public.articulos_cambios enable row level security;
drop policy if exists articulos_cambios_leer on public.articulos_cambios;
create policy articulos_cambios_leer on public.articulos_cambios
  for select to authenticated using (true);
revoke all on public.articulos_cambios from anon, authenticated;
grant select on public.articulos_cambios to authenticated;
grant select, insert on public.articulos_cambios to service_role;

create or replace function public.trg_articulos_cambios()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  -- Columnas que NO se anotan: stock (lo lleva el kardex), internas y los *_id
  -- de taxonomía/proveedor/marca (se anota el nombre, que se lee mejor).
  v_fuera text[] := array[
    'id', 'created_at', 'updated_at', 'fecha_actualizacion', 'search_text', 'embedding',
    'stock_actual', 'stock_reservado', 'creado_por', 'actualizado_por',
    'proveedor_id', 'marca_id', 'rubro_id', 'categoria_id', 'subcategoria_id'
  ];
  v_n   jsonb := to_jsonb(new);
  v_o   jsonb := to_jsonb(old);
  v_uid uuid  := coalesce(
    auth.uid(),
    case when new.actualizado_por is distinct from old.actualizado_por then new.actualizado_por end
  );
  v_via text  := coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role', current_user::text);
  k     text;
begin
  begin
    for k in select jsonb_object_keys(v_n) loop
      if k = any(v_fuera) then continue; end if;
      if (v_n -> k) is distinct from (v_o -> k) then
        insert into articulos_cambios (articulo_id, campo, antes, despues, usuario_id, via)
        values (new.id, k, v_o ->> k, v_n ->> k, v_uid, v_via);
      end if;
    end loop;
  exception when others then
    -- Nunca frenar la carga de un artículo por el historial.
    raise warning 'trg_articulos_cambios: %', sqlerrm;
  end;
  return null;
end;
$fn$;

drop trigger if exists trg_articulos_cambios on public.articulos;
create trigger trg_articulos_cambios
  after update on public.articulos
  for each row execute function public.trg_articulos_cambios();

-- El historial no se edita ni se borra (ni siquiera con la clave de servicio).
create or replace function public.trg_articulos_cambios_inmutable()
returns trigger
language plpgsql as $fn$
begin
  raise exception 'articulos_cambios es un historial: no se modifica ni se borra';
end;
$fn$;

drop trigger if exists trg_articulos_cambios_inmutable on public.articulos_cambios;
create trigger trg_articulos_cambios_inmutable
  before update or delete on public.articulos_cambios
  for each row execute function public.trg_articulos_cambios_inmutable();

