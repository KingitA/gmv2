-- Antes del alta / cambio: completa quién (y que nadie lo pueda falsear desde el cuerpo del pedido)
create or replace function public.trg_vencimientos_quien()
returns trigger
language plpgsql as $fn$
declare
  v_uid uuid := auth.uid();
begin
  if tg_op = 'INSERT' then
    new.creado_por      := coalesce(v_uid, new.creado_por);
    new.actualizado_por := coalesce(v_uid, new.actualizado_por, new.creado_por);
    new.pagado_por      := case when new.estado = 'pagado' then new.actualizado_por end;
    new.pagado_at       := case when new.estado = 'pagado' then now() end;
    return new;
  end if;

  new.creado_por := old.creado_por;
  if (new.estado, new.monto, new.fecha_vencimiento) is distinct from (old.estado, old.monto, old.fecha_vencimiento) then
    if v_uid is not null then
      new.actualizado_por := v_uid;
    elsif new.actualizado_por is not distinct from old.actualizado_por then
      -- El servidor no dijo quién: no dejar al de un cambio anterior
      new.actualizado_por := null;
    end if;
  end if;

  if new.estado = 'pagado' and old.estado is distinct from 'pagado' then
    new.pagado_por := new.actualizado_por;
    new.pagado_at  := now();
  elsif new.estado is distinct from 'pagado' then
    new.pagado_por := null;
    new.pagado_at  := null;
  else
    new.pagado_por := old.pagado_por;
    new.pagado_at  := old.pagado_at;
  end if;
  return new;
end;
$fn$;

drop trigger if exists trg_vencimientos_quien on public.vencimientos;
create trigger trg_vencimientos_quien
  before insert or update on public.vencimientos
  for each row execute function public.trg_vencimientos_quien();

-- Después del alta / cambio: una fila de historial
create or replace function public.trg_vencimientos_historial()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_via text := coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role', current_user::text);
begin
  begin
    if tg_op = 'INSERT' then
      insert into vencimientos_historial (vencimiento_id, estado_anterior, estado_nuevo, monto_anterior, monto_nuevo, fecha_anterior, fecha_nueva, orden_pago_id, usuario_id, via)
      values (new.id, null, new.estado, null, new.monto, null, new.fecha_vencimiento, new.orden_pago_id, new.creado_por, v_via);
    elsif (new.estado, new.monto, new.fecha_vencimiento) is distinct from (old.estado, old.monto, old.fecha_vencimiento) then
      insert into vencimientos_historial (vencimiento_id, estado_anterior, estado_nuevo, monto_anterior, monto_nuevo, fecha_anterior, fecha_nueva, orden_pago_id, usuario_id, via)
      values (new.id, old.estado, new.estado, old.monto, new.monto, old.fecha_vencimiento, new.fecha_vencimiento, new.orden_pago_id, new.actualizado_por, v_via);
    end if;
  exception when others then
    -- Nunca frenar un pago por el historial.
    raise warning 'trg_vencimientos_historial: %', sqlerrm;
  end;
  return null;
end;
$fn$;

drop trigger if exists trg_vencimientos_historial on public.vencimientos;
create trigger trg_vencimientos_historial
  after insert or update on public.vencimientos
  for each row execute function public.trg_vencimientos_historial();

